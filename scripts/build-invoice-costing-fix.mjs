// One-off data fix for the Nov 2026 landed-cost method: re-splits the freight of FINAL invoices that cover several products by
// gross weight (packing list) and stores the weights. Output is idempotent SQL keyed by invoice number and product name,
// so the same file works on TEST and PRODUCTION. Usage: node scripts/build-invoice-costing-fix.mjs <folder with the final .xls/.xlsx> <final_lines.json> [out.sql]
// final_lines.json = rows { inv, lt, d, q, a, al, prod } of dtc_invoice_lines of every final invoice (select ... where doc_type = 'final').
import fs from 'fs'; import path from 'path'; import * as XLSX from 'xlsx';
import { parseInvoiceSheets } from '../src/invoices/parse.js';
import { allocateByWeight } from '../src/invoices/plan.js';

const [dir, linesFile, out = new URL('../data_invoice_costing_fix.sql', import.meta.url).pathname] = process.argv.slice(2);
const db = JSON.parse(fs.readFileSync(linesFile, 'utf8'));
const q = v => (v == null ? 'NULL' : typeof v === 'number' ? String(v) : "'" + String(v).replace(/'/g, "''") + "'");
const norm = s => String(s).toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
const r2 = n => Math.round(n * 100) / 100;
const sql = [`-- HVI CRM — landed-cost method fix (Nov 2026). Generated by scripts/build-invoice-costing-fix.mjs. Idempotent.
-- Run AFTER migration_invoice_costing.sql. Re-splits the freight of final invoices that cover several products by GROSS WEIGHT
-- (packing list) instead of the pro-forma charge, stores the weights, and refreshes each product's cost and final balance.
`];
const touched = new Set();

for (const f of fs.readdirSync(dir).filter(x => /^final invoice.*\.(xls|xlsx)$/i.test(x))) {
  const wb = XLSX.read(fs.readFileSync(path.join(dir, f)), { type: 'buffer', cellDates: true });
  const parsed = parseInvoiceSheets(wb.SheetNames.map(n => ({ name: n, rows: XLSX.utils.sheet_to_json(wb.Sheets[n], { header: 1, raw: true, defval: '' }) })), { fileName: f });
  const inv = parsed.invoiceNumber;
  const lines = db.filter(r => r.inv === inv);
  if (!lines.length) { console.log(`skip ${inv}: not in the database`); continue; }
  const ship = lines.filter(l => l.lt === 'shipping' && l.al === 'dtc');
  const prods = [...new Set(ship.map(l => l.prod))];
  const plines = lines.filter(l => l.lt === 'product' && l.al === 'dtc');
  const weightOf = l => parsed.packing.find(p => norm(p.description) === norm(l.d));
  const gross = new Map(), cbm = new Map();
  for (const l of plines) { const p = weightOf(l); if (p) { gross.set(l.prod, (gross.get(l.prod) || 0) + (p.grossKg || 0)); cbm.set(l.prod, (cbm.get(l.prod) || 0) + (p.cbm || 0)); } }
  const total = r2(ship.reduce((a, l) => a + Number(l.a), 0));
  if (prods.length < 2 || !prods.every(p => gross.get(p) > 0)) { console.log(`skip ${inv}: ${prods.length} product(s) / no weights for all (single-product invoices keep their full freight)`); continue; }
  const alloc = allocateByWeight(total, prods.map(p => ({ productId: p, weight: gross.get(p) })));
  const totalKg = [...gross.values()].reduce((a, b) => a + b, 0);
  sql.push(`-- ${inv}: freight ${total} split by gross weight (${totalKg} kg)`);
  for (const l of plines) { const p = weightOf(l); if (p) sql.push(`UPDATE dtc_invoice_lines l SET gross_weight_kg = ${p.grossKg}, cbm = ${p.cbm} FROM dtc_invoices i WHERE l.invoice_id = i.id AND i.invoice_number = ${q(inv)} AND i.doc_type = 'final' AND l.line_type = 'product' AND l.description = ${q(l.d)};`); }
  for (const a of alloc.parts) {
    const pct = r2(gross.get(a.productId) / totalKg * 100);
    sql.push(`UPDATE dtc_invoice_lines l SET amount = ${a.amount}, alloc_basis = 'gross_weight', note = ${q(`${prods.length}-way split of ${total} by gross weight on the packing list (${pct}%).`)} FROM dtc_invoices i, dtc_products p WHERE l.invoice_id = i.id AND i.invoice_number = ${q(inv)} AND i.doc_type = 'final' AND l.line_type = 'shipping' AND l.dtc_product_id = p.id AND p.name = ${q(a.productId)};`);
    touched.add(JSON.stringify([inv, a.productId]));
  }
  sql.push('');
}
// refresh the product cost and final balance from the invoice lines
sql.push('-- Product cost = every line of the final invoice allocated to the product; final balance = cost − deposit');
for (const t of touched) {
  const [inv, name] = JSON.parse(t);
  // guarded: a database without this invoice's lines is left untouched
  const has = `EXISTS (SELECT 1 FROM dtc_invoice_lines l JOIN dtc_invoices i ON i.id = l.invoice_id WHERE i.invoice_number = ${q(inv)} AND i.doc_type = 'final' AND l.dtc_product_id = p.id AND l.allocation = 'dtc')`;
  sql.push(`UPDATE dtc_products p SET est_cost = (SELECT round(sum(l.amount), 2) FROM dtc_invoice_lines l JOIN dtc_invoices i ON i.id = l.invoice_id WHERE i.invoice_number = ${q(inv)} AND i.doc_type = 'final' AND l.dtc_product_id = p.id AND l.allocation = 'dtc') WHERE p.name = ${q(name)} AND ${has};`);
  sql.push(`UPDATE dtc_financials f SET final_amount = round(p.est_cost - coalesce(f.deposit_amount, 0), 2) FROM dtc_products p WHERE f.dtc_product_id = p.id AND p.name = ${q(name)} AND f.invoice_number = ${q(inv)} AND ${has};`);
}
fs.writeFileSync(out, sql.join('\n') + '\n');
console.log('wrote', out, '·', touched.size, 'products');
