// One-off loader: runs the real invoice files through the same planner the app uses and prints / emits SQL.
// Usage: node scripts/build-invoice-history.mjs "<folder with .xls/.xlsx>" [--sql out.sql]
import fs from 'fs'; import path from 'path'; import crypto from 'crypto'; import * as XLSX from 'xlsx';
import { parseInvoiceSheets } from '../src/invoices/parse.js';
import { buildPlan } from '../src/invoices/plan.js';
import { normKey } from '../src/invoices/match.js';
import { HISTORY_PRODUCTS, FORCED, ALLOCATION_OVERRIDES, PAYMENTS } from './invoice-history-config.mjs';

const dir = process.argv[2];
const sqlOut = process.argv.includes('--sql') ? process.argv[process.argv.indexOf('--sql') + 1] : null;
const files = fs.readdirSync(dir).filter(f => /\.(xls|xlsx)$/i.test(f)).map(f => path.join(dir, f));
const products = HISTORY_PRODUCTS.map((p, i) => ({ id: 'P' + i, name: p.name, order_ref: p.ref }));
const productAttrs = new Map(HISTORY_PRODUCTS.map(p => [p.name, p]));
const byName = new Map(products.map(p => [p.name, p]));
const docs = files.map(f => {
  const wb = XLSX.read(fs.readFileSync(f), { type: 'buffer', cellDates: true });
  const sheets = wb.SheetNames.map(n => ({ name: n, rows: XLSX.utils.sheet_to_json(wb.Sheets[n], { header: 1, raw: true, defval: '' }) }));
  return { file: path.basename(f), hash: crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex'), parsed: parseInvoiceSheets(sheets, { fileName: path.basename(f) }) };
}).sort((a, b) => (a.parsed.invoiceDate + a.parsed.docType).localeCompare(b.parsed.invoiceDate + b.parsed.docType));

const aliases = []; const prior = []; const results = [];
for (const d of docs) {
  const forced = {};
  for (const [desc, name] of Object.entries(FORCED[d.file] || {})) forced[desc] = byName.get(name)?.id;
  const plan = buildPlan({ parsed: d.parsed, fileName: d.file, products, aliases, priorInvoices: prior, forcedMap: forced, allocationOverrides: ALLOCATION_OVERRIDES[d.file] || {} });
  results.push({ d, plan });
  prior.push({ id: 'I' + prior.length, manufacturer: d.parsed.manufacturerGuess, invoice_number: d.parsed.invoiceNumber, doc_type: d.parsed.docType, refs: d.parsed.refs,
    lines: plan.rows.filter(r => r.productId && r.allocation === 'dtc').map(r => ({ line_type: r.lineType, quantity: r.quantity, unit_price: r.unitPrice, amount: r.amount, dtc_product_id: r.productId })) });
  for (const r of plan.rows) if (r.productId && r.lineType === 'product' && r.how !== 'alias') aliases.push({ alias_norm: normKey(r.description), dtc_product_id: r.productId });
}
const nameOf = id => products.find(p => p.id === id)?.name || '—';
if (!sqlOut) {
  for (const { d, plan } of results) {
    console.log(`\n### ${d.file}\n  ${plan.header.docType} ${plan.header.invoiceNumber} ${plan.header.invoiceDate} total=${plan.header.total} deposits=${plan.header.depositTotal} overpaid=${plan.header.overpaid} balance=${plan.header.balance}`);
    for (const r of plan.rows) console.log(`  [${r.lineType.padEnd(11)}|${r.allocation}] ${r.description.slice(0, 44).padEnd(44)} ${String(r.quantity ?? '').padStart(4)} x ${String(r.unitPrice ?? '').padStart(5)} = ${String(r.amount).padStart(8)} -> ${nameOf(r.productId).padEnd(32)} ${r.confidence}/${r.how}${r.splitOf != null ? ' (split)' : ''}`);
    for (const p of plan.productsFin) console.log(`   FIN ${nameOf(p.productId).padEnd(32)} goods=${p.goods} photo=${p.photography} ship=${p.shipping} fees=${p.fees} total=${p.total} units=${p.units} deposit=${p.deposit} (${p.depositBasis}) final=${p.final}`);
    for (const w of plan.warnings) console.log(`   ${w.level.toUpperCase()}: ${w.msg}`);
  }
}

// ── SQL emission ───────────────────────────────────────────────────────────
if (sqlOut) {
  const q = v => (v === null || v === undefined || v === '' ? 'NULL' : typeof v === 'number' ? String(v) : "'" + String(v).replace(/'/g, "''") + "'");
  const pid = name => `(SELECT id FROM dtc_products WHERE name = ${q(name)} LIMIT 1)`;
  const out = [];
  out.push(`-- HVI CRM — DTC invoice history (Q3 2026 invoices from Bing Bing), generated by scripts/build-invoice-history.mjs
-- Run in the TEST Supabase SQL editor AFTER migration_dtc_invoices.sql. Idempotent: re-running changes nothing.
-- Source files: 15 supplier documents (pro-forma and final invoices) cross-checked with the Gmail threads.
-- Product matches that were NOT certain are listed in docs/invoice-history-review.md and in each invoice's "warnings".
`);
  out.push('-- 1. Products referenced by the invoices (only created when the name is missing)');
  for (const [name, a] of productAttrs) {
    out.push(`INSERT INTO dtc_products (name, product_type, category, phase, manufacturer, order_ref, phase_changed_at, last_activity)
SELECT ${q(name)}, ${q(a.type)}, ${q(a.category)}, ${q(a.phase)}, ${q(a.mfr)}, ${q(a.ref)}, current_date, current_date
WHERE NOT EXISTS (SELECT 1 FROM dtc_products WHERE name = ${q(name)});
UPDATE dtc_products SET order_ref = ${q(a.ref)} WHERE name = ${q(name)} AND (order_ref IS NULL OR order_ref = '');
INSERT INTO dtc_financials (dtc_product_id, product_name, manufacturer)
SELECT id, name, manufacturer FROM dtc_products WHERE name = ${q(name)} AND NOT EXISTS (SELECT 1 FROM dtc_financials f WHERE f.dtc_product_id = dtc_products.id);`);
  }
  out.push('\n-- 2. Invoices and their lines');
  for (const { d, plan } of results) {
    const h = plan.header, pr = d.parsed;
    const unresolved = plan.rows.filter(r => r.lineType === 'product' && r.allocation === 'dtc' && !r.productId).length;
    if (unresolved) throw new Error(`${d.file}: ${unresolved} unresolved product line(s)`);
    out.push(`
-- ${d.file}
INSERT INTO dtc_invoices (manufacturer, invoice_number, doc_type, invoice_date, currency, total_amount, deposit_paid, overpaid_amount, balance_due, deposits, refs, file_name, file_hash, extraction_method, warnings, created_by)
VALUES (${q(h.manufacturer)}, ${q(h.invoiceNumber)}, ${q(h.docType)}, ${q(h.invoiceDate)}, 'USD', ${q(h.total)}, ${q(pr.totals.deposit || null)}, ${q(pr.totals.overpaid || null)}, ${q(pr.totals.balance != null ? Math.round(pr.totals.balance * 100) / 100 : null)},
  ${q(JSON.stringify(pr.totals.deposits))}::jsonb, ARRAY[${h.refs.map(q).join(',')}]::text[], ${q(d.file)}, ${q(d.hash)}, 'history', ${q(JSON.stringify(plan.warnings.filter(w => w.level !== 'info')))}::jsonb, 'history load')
ON CONFLICT (manufacturer, invoice_number, doc_type) DO NOTHING;
INSERT INTO dtc_invoice_lines (invoice_id, position, description, line_type, quantity, unit_price, amount, packed_quantity, dtc_product_id, allocation, split_of, note)
SELECT inv.id, v.position, v.description, v.line_type, v.quantity, v.unit_price, v.amount, v.packed_quantity, v.pid, v.allocation, v.split_of, v.note
FROM (SELECT id FROM dtc_invoices WHERE manufacturer = ${q(h.manufacturer)} AND invoice_number = ${q(h.invoiceNumber)} AND doc_type = ${q(h.docType)}) inv
CROSS JOIN (VALUES
${plan.rows.map((r, i) => `  (${i}, ${q(r.description)}, ${q(r.lineType)}, ${q(r.quantity)}::numeric, ${q(r.unitPrice)}::numeric, ${q(r.amount)}::numeric, ${q(r.packedQuantity)}::numeric, ${r.productId && r.allocation === 'dtc' ? pid(nameOf(r.productId)) : 'NULL::uuid'}, ${q(r.allocation)}, ${q(r.splitOf)}::integer, ${q((r.note || '').trim())})`).join(',\n')}
) AS v(position, description, line_type, quantity, unit_price, amount, packed_quantity, pid, allocation, split_of, note)
WHERE NOT EXISTS (SELECT 1 FROM dtc_invoice_lines l WHERE l.invoice_id = inv.id);`);
  }
  out.push('\n-- 3. Names confirmed during the load');
  const seen = new Set();
  for (const a of aliases) {
    const k = a.alias_norm + '|' + a.dtc_product_id; if (seen.has(k) || !a.alias_norm) continue; seen.add(k);
    out.push(`INSERT INTO dtc_product_aliases (alias_norm, alias_text, dtc_product_id) SELECT ${q(a.alias_norm)}, ${q(a.alias_norm)}, ${pid(nameOf(a.dtc_product_id))} WHERE ${pid(nameOf(a.dtc_product_id))} IS NOT NULL ON CONFLICT DO NOTHING;`);
  }
  out.push('\n-- 4. Financial records per product: latest document wins (final over pro-forma)');
  const best = new Map();
  for (const { d, plan } of results) for (const pf of plan.productsFin) {
    const cur = best.get(pf.productId); const rank = d.parsed.docType === 'final' ? 2 : 1;
    if (!cur || rank >= cur.rank) best.set(pf.productId, { rank, d, pf, plan });
  }
  for (const [id, { d, pf, plan }] of best) {
    const name = nameOf(id), pay = PAYMENTS[name] || {};
    const final = d.parsed.docType === 'final';
    const piDoc = results.find(x => x.d.parsed.docType === 'proforma' && x.plan.productsFin.some(p => p.productId === id));
    const approxDate = piDoc ? piDoc.d.parsed.invoiceDate : d.parsed.invoiceDate;
    const notes = [`Loaded from ${d.parsed.docType} invoice ${d.parsed.invoiceNumber} (${d.parsed.invoiceDate}).`, pf.depositBasis ? `Deposit: ${pf.depositBasis}.` : '',
      pay.note || '', final && pf.depositPaid && !pay.deposit_paid_date ? `Deposit is listed as paid on the final invoice; the date shown is the ${piDoc ? 'pro-forma' : 'final invoice'} date (${approxDate}) and must be confirmed from the payment confirmation.` : '',
      final && !pay.final_paid_date && !pay.paid_in_full ? 'Final payment date not recorded.' : ''].filter(Boolean).join(' ');
    const depDate = pay.deposit_paid_date || (final && pf.depositPaid ? approxDate : null);
    const paidFull = !!pay.paid_in_full;
    out.push(`UPDATE dtc_financials SET order_number = ${q(pf.refs.join(' '))}, invoice_number = ${q(d.parsed.invoiceNumber)},
  deposit_amount = ${paidFull ? 'NULL' : q(pf.deposit)}, deposit_paid_date = ${paidFull ? 'NULL' : q(depDate)},
  final_amount = ${q(paidFull ? pf.total : pf.final)}, final_paid_date = ${q(pay.final_paid_date)},
  paid_in_full = ${paidFull}, full_payment_date = ${q(pay.full_payment_date)}, notes = ${q(notes)}
WHERE dtc_product_id = ${pid(name)};
UPDATE dtc_products SET units_ordered = ${q(pf.units || null)}, est_cost = ${q(pf.total)}, units = coalesce(units, ${q(pf.units || null)}) WHERE name = ${q(name)};`);
  }
  out.push(`\nSELECT i.invoice_number, i.doc_type, i.invoice_date, i.total_amount, count(l.*) AS lines, round(sum(l.amount) FILTER (WHERE l.allocation = 'dtc'), 2) AS dtc_amount, round(sum(l.amount) FILTER (WHERE l.allocation = 'b2b'), 2) AS b2b_amount
FROM dtc_invoices i LEFT JOIN dtc_invoice_lines l ON l.invoice_id = i.id GROUP BY i.id ORDER BY i.invoice_date, i.doc_type;`);
  fs.mkdirSync(path.dirname(sqlOut), { recursive: true });
  fs.writeFileSync(sqlOut, out.join('\n') + '\n');
  console.log('wrote', sqlOut, fs.statSync(sqlOut).size, 'bytes');
}
export { results, products, docs };
